pub fn is_supported(vid: u16, pid: u16) -> bool {
    USB_IDS.contains(&(vid, pid))
}

pub fn model(cid: u8, mid: u8) -> Option<&'static Model> {
    MODELS.binary_search_by_key(&(cid, mid), |m| (m.cid, m.mid)).ok().map(|i| &MODELS[i])
}

